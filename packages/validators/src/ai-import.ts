export const DEFAULT_IMPORT_SUMMARY_KEYWORDS = [
  "total",
  "subtotal",
  "sub-total",
  "grand total",
  "total general",
  "resumen",
  "合计",
  "总计",
  "小计",
];

export function parseLocalizedNumericCell(
  rawCell: string | undefined,
  decimalSeparator: "." | ",",
): number | null {
  if (!rawCell) return null;
  let cleaned = String(rawCell)
    .trim()
    .replace(/[$€¥￥%]/g, "")
    .replace(
      /\bBs\.(?=\s|\d|$)|\b(?:USD|CNY|RMB|EUR|VES|Bs|KG|CBM|PCS|CTNS?)\b/gi,
      "",
    )
    .replace(/\s+/g, "");

  if (!cleaned) return null;

  if (decimalSeparator === ",") {
    cleaned = cleaned.replace(/\./g, "").replace(",", ".");
  } else if (/^\d+,\d{1,2}$/.test(cleaned) && !cleaned.includes(".")) {
    cleaned = cleaned.replace(",", ".");
  } else {
    cleaned = cleaned.replace(/,/g, "");
  }

  const parsed = Number(cleaned);
  return Number.isFinite(parsed) ? parsed : null;
}

export function isImportSummaryOrFooterRow(
  row: readonly string[],
  keywords: readonly string[] = DEFAULT_IMPORT_SUMMARY_KEYWORDS,
  nameColIdx?: number,
  skuColIdx?: number,
): boolean {
  const nonEmptyCells = row
    .map((c) => String(c).trim())
    .filter((c) => c.length > 0);
  if (nonEmptyCells.length === 0) return true;

  const firstText = (nonEmptyCells[0] ?? "").toLowerCase();
  const nameText =
    nameColIdx !== undefined
      ? String(row[nameColIdx] ?? "")
          .trim()
          .toLowerCase()
      : "";
  const skuText =
    skuColIdx !== undefined
      ? String(row[skuColIdx] ?? "")
          .trim()
          .toLowerCase()
      : "";

  for (const kw of keywords) {
    const lowerKw = kw.toLowerCase();
    if (
      firstText === lowerKw ||
      firstText.startsWith(`${lowerKw}:`) ||
      firstText.startsWith(`${lowerKw} `) ||
      nameText === lowerKw ||
      (skuText === "" && nameText.startsWith(`${lowerKw} `))
    ) {
      return true;
    }
  }
  return false;
}

/**
 * Deterministically compiles all data rows below `schema.headerRowIndex` into
 * canonical `ExtractedDocumentItem[]` with exact `roundMoney2` cost rounding,
 * packaging multiplication, footer suppression, and optional SKU autogeneration.
 * Safe in both browser `"use client"` hooks and server-side Node routes.
 */
export function compileTabularRowsDeterministically(
  allSheetRows: readonly string[][],
  schema: Pick<
    InferredTabularSchemaResult,
    | "headerRowIndex"
    | "columnMapping"
    | "transformRules"
    | "ignoreSummaryKeywords"
    | "confidence"
  >,
): ExtractedDocumentItem[] {
  const items: ExtractedDocumentItem[] = [];
  const map = schema.columnMapping;
  const rules = schema.transformRules;
  const keywords =
    schema.ignoreSummaryKeywords.length > 0
      ? schema.ignoreSummaryKeywords
      : DEFAULT_IMPORT_SUMMARY_KEYWORDS;

  const getStr = (
    row: readonly string[],
    field: CanonicalImportField,
  ): string => {
    const idx = map[field];
    if (idx === undefined) return "";
    return String(row[idx] ?? "").trim();
  };

  for (let r = schema.headerRowIndex + 1; r < allSheetRows.length; r++) {
    const row = allSheetRows[r];
    if (!row) continue;

    if (isImportSummaryOrFooterRow(row, keywords, map.name, map.sku)) {
      continue;
    }

    const rawSku = getStr(row, "sku").slice(0, 64);
    const rawName = getStr(row, "name").slice(0, 512);
    const rawBrand = getStr(row, "brand").slice(0, 256);
    const rawCategory = getStr(row, "category").slice(0, 256);
    const rawBarcode = getStr(row, "barcode").slice(0, 128);
    const rawDesc = getStr(row, "description").slice(0, 2000);

    if (!rawName && !rawSku) {
      continue;
    }

    const rowNumber = r + 1;
    const effectiveName = rawName || rawSku;
    const skuAutoGenerated = rawSku.length === 0;
    const effectiveSku = skuAutoGenerated
      ? suggestDeterministicSku({
          name: effectiveName,
          brand: rawBrand || null,
          category: rawCategory || null,
          rowNumber,
        })
      : rawSku;

    const bultosNum = parseLocalizedNumericCell(
      getStr(row, "bultos"),
      rules.decimalSeparator,
    );
    const cajasNum = parseLocalizedNumericCell(
      getStr(row, "cajasPerBulk"),
      rules.decimalSeparator,
    );
    const unidCajaNum = parseLocalizedNumericCell(
      getStr(row, "unidPerCaja"),
      rules.decimalSeparator,
    );
    const presNum = parseLocalizedNumericCell(
      getStr(row, "presentacion"),
      rules.decimalSeparator,
    );
    const directQtyNum = parseLocalizedNumericCell(
      getStr(row, "quantity"),
      rules.decimalSeparator,
    );

    const bultos =
      bultosNum !== null && bultosNum >= 0 ? Math.trunc(bultosNum) : undefined;
    const cajasPerBulk =
      cajasNum !== null && cajasNum >= 1 ? Math.trunc(cajasNum) : null;
    const unidPerCaja =
      unidCajaNum !== null && unidCajaNum >= 1 ? Math.trunc(unidCajaNum) : null;
    const presentacion =
      presNum !== null && presNum >= 1 ? Math.trunc(presNum) : 1;

    let quantity = 0;
    if (
      rules.unitsFormula === "bultos_x_cajas_x_unid" &&
      bultos !== undefined
    ) {
      quantity =
        bultos * (cajasPerBulk ?? 1) * (unidPerCaja ?? 1) * presentacion;
    } else if (directQtyNum !== null) {
      quantity = Math.max(0, Math.trunc(directQtyNum));
    } else if (bultos !== undefined) {
      quantity =
        bultos * (cajasPerBulk ?? 1) * (unidPerCaja ?? 1) * presentacion;
    }

    const rawCostNum = parseLocalizedNumericCell(
      getStr(row, "cost"),
      rules.decimalSeparator,
    );
    const unitCost =
      rawCostNum !== null && rawCostNum >= 0 ? roundMoney2(rawCostNum) : null;

    const rawWeight = parseLocalizedNumericCell(
      getStr(row, "weight"),
      rules.decimalSeparator,
    );
    const rawVolume = parseLocalizedNumericCell(
      getStr(row, "volume"),
      rules.decimalSeparator,
    );

    items.push({
      rowNumber,
      sku: effectiveSku,
      skuAutoGenerated,
      name: effectiveName,
      nameOriginal: rawName || undefined,
      barcode: rawBarcode || undefined,
      categoryRaw: rawCategory || undefined,
      brandRaw: rawBrand || undefined,
      quantity,
      bultos,
      cajasPerBulk,
      unidPerCaja,
      unitCost,
      currency: rules.currency,
      weightKg: rawWeight !== null && rawWeight >= 0 ? rawWeight : null,
      volumeCbm: rawVolume !== null && rawVolume >= 0 ? rawVolume : null,
      description: rawDesc || undefined,
      confidence: schema.confidence,
    });
  }

  return items;
}
