/**
 * Normalizes a spreadsheet column header for deterministic alias & fingerprint matching:
 * strips accents, asterisks, punctuation noise, collapses spaces, and lowercases.
 */
export function normalizeImportHeaderToken(raw: string): string {
  return String(raw)
    .trim()
    .toLowerCase()
    .normalize("NFKC")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[*#:()[\]]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function fnv1aHex32(input: string, seed: number): string {
  let hash = seed >>> 0;
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

/**
 * Computes a deterministic 64-character hex structural fingerprint of a sheet's
 * header columns (preserving non-empty normalized header order and count) without
 * requiring `node:crypto`, so browser wizards and server procedures produce the
 * exact same key.
 */
export function computeHeaderFingerprint(headers: readonly string[]): string {
  const canonical = headers
    .map((h, idx) => `${idx}:${normalizeImportHeaderToken(h)}`)
    .filter((entry) => !entry.endsWith(":"))
    .join("|");

  if (canonical.length === 0) {
    return "0".repeat(64);
  }

  // Eight independent 32-bit FNV-1a projections -> 64 hex chars (256-bit signature)
  const seeds = [
    0x811c9dc5, 0xdeadbeef, 0x9e3779b9, 0x85ebca6b, 0xc2b2ae35, 0x27d4eb2f,
    0x165667b1, 0xd3a2646c,
  ];
  return seeds
    .map((seed, idx) => fnv1aHex32(`${idx}#${canonical}`, seed))
    .join("");
}

function cleanCodeSegment(raw: string | null | undefined, len: number): string {
  if (!raw) return "";
  const ascii = raw
    .normalize("NFKC")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "");
  return ascii.slice(0, len);
}

/**
 * Generates an editable, collision-resistant deterministic SKU (`<= 32` chars)
 * when an uploaded catalog, inventory sheet, or PDF lacks an explicit SKU column.
 * Marked in UI with `skuAutoGenerated: true` so the operator can edit or accept it.
 */
export function suggestDeterministicSku(params: {
  name: string;
  brand?: string | null;
  category?: string | null;
  rowNumber: number;
}): string {
  const prefix =
    cleanCodeSegment(params.brand, 3) ||
    cleanCodeSegment(params.category, 3) ||
    "GEN";
  const nameSeg = cleanCodeSegment(params.name, 4) || "ITEM";
  const digest = fnv1aHex32(
    `${params.brand ?? ""}|${params.category ?? ""}|${params.name.trim().toLowerCase()}`,
    0x811c9dc5,
  )
    .slice(0, 4)
    .toUpperCase();
  const seq = String(Math.max(1, Math.trunc(params.rowNumber))).padStart(
    4,
    "0",
  );
  return `AUTO-${prefix}-${nameSeg}-${digest}-${seq}`.slice(0, 64);
}

