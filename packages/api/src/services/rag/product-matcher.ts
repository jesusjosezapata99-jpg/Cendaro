import type { getDb } from "@cendaro/db/client";
import type { CatalogSemanticMatchResult } from "@cendaro/validators";
import {
  Brand,
  Category,
  CategoryAlias,
  Product,
  ProductEmbedding,
} from "@cendaro/db/schema";

import { logger } from "../../logger";
import { runInWorkspaceRls, runInWorkspaceRlsReadonly } from "../../trpc";
import { sha256Hex } from "./audit";
import { cosineSimilarity, generateEmbeddings } from "./embeddings";

type Db = ReturnType<typeof getDb>;

export interface MatchableImportCandidate {
  sku?: string | null;
  skuAutoGenerated?: boolean;
  name: string;
  nameOriginal?: string | null;
  barcode?: string | null;
  categoryRaw?: string | null;
  brandRaw?: string | null;
}

interface WorkspaceCatalogRow {
  id: string;
  sku: string;
  barcode: string | null;
  name: string;
  descriptionShort: string | null;
  categoryId: string | null;
  brandId: string | null;
  categoryName: string | null;
  brandName: string | null;
}

function isUndefinedTableError(err: unknown): boolean {
  const code =
    (err as { code?: string } | null)?.code ??
    (err as { cause?: { code?: string } } | null)?.cause?.code;
  return code === "42P01";
}

function normalizeCodeKey(value: string | null | undefined): string {
  if (!value) return "";
  return value
    .trim()
    .toUpperCase()
    .replace(/[\s-]+/g, "");
}

const LEXICAL_STOPWORDS = new Set([
  "de",
  "del",
  "la",
  "el",
  "los",
  "las",
  "para",
  "con",
  "en",
  "por",
  "un",
  "una",
  "the",
  "of",
  "for",
  "with",
  "and",
]);

function normalizeTextTokens(value: string): Set<string> {
  const clean = value
    .toLowerCase()
    .normalize("NFKC")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
  const matches = clean.match(/[\p{L}\p{N}]+/gu) ?? [];
  const out = new Set<string>();
  for (const tok of matches) {
    if (LEXICAL_STOPWORDS.has(tok)) continue;
    if (tok.length >= 2 || /^\d+$/.test(tok)) {
      out.add(tok);
    }
  }
  return out;
}

function lexicalSimilarityScore(a: Set<string>, b: Set<string>): number {
  if (a.size === 0 || b.size === 0) return 0;
  let intersection = 0;
  for (const tok of a) {
    if (b.has(tok)) intersection++;
  }
  if (intersection === 0) return 0;
  const dice = (2 * intersection) / (a.size + b.size);
  const minSize = Math.min(a.size, b.size);
  if (minSize >= 2) {
    const containment = intersection / minSize;
    return dice * 0.55 + containment * 0.45;
  }
  return dice;
}

export function buildProductSearchDocument(prod: {
  sku?: string | null;
  name?: string | null;
  brandName?: string | null;
  categoryName?: string | null;
  barcode?: string | null;
  descriptionShort?: string | null;
}): { searchDocument: string; contentHash: string } {
  const cleanSku = (prod.sku ?? "").trim();
  const cleanName = (prod.name ?? "").trim();
  const parts = [
    cleanSku ? `SKU: ${cleanSku}` : "",
    cleanName ? `Producto: ${cleanName}` : "",
    prod.brandName ? `Marca: ${prod.brandName.trim()}` : "",
    prod.categoryName ? `Categoría: ${prod.categoryName.trim()}` : "",
    prod.barcode ? `EAN: ${prod.barcode.trim()}` : "",
    prod.descriptionShort ? prod.descriptionShort.trim().slice(0, 200) : "",
  ].filter((p) => p.length > 0);

  const searchDocument = parts.join(" | ");
  const contentHash = sha256Hex(searchDocument);
  return { searchDocument, contentHash };
}

/**
 * Synchronizes `public.product_embedding` for a workspace (or a subset of `productIds`),
 * computing embeddings ONLY for products whose `content_hash` is missing or changed.
 * Safe to invoke from `ctx.afterCommit` or before semantic matching.
 */
export async function syncWorkspaceProductEmbeddings(
  poolDb: Db,
  workspaceId: string,
  options?: {
    productIds?: readonly string[];
    maxBatchLimit?: number;
  },
): Promise<{
  synced: number;
  skippedUnchanged: number;
  tableAvailable: boolean;
}> {
  if (
    typeof (poolDb as unknown as { transaction?: unknown }).transaction !==
    "function"
  ) {
    return { synced: 0, skippedUnchanged: 0, tableAvailable: false };
  }
  const maxLimit = options?.maxBatchLimit ?? 300;

  let catalogRows: WorkspaceCatalogRow[] = [];
  let existingHashes = new Map<string, string>();
  let tableAvailable = true;

  try {
    await runInWorkspaceRlsReadonly(poolDb, workspaceId, async (tx) => {
      const productFilter =
        options?.productIds && options.productIds.length > 0
          ? and(
              eq(Product.workspaceId, workspaceId),
              inArray(Product.id, [...options.productIds]),
            )
          : eq(Product.workspaceId, workspaceId);

      // Sequential queries on single `tx` PoolClient (zero socket queue contention)
      const products = await tx
        .select({
          id: Product.id,
          sku: Product.sku,
          barcode: Product.barcode,
          name: Product.name,
          descriptionShort: Product.descriptionShort,
          categoryId: Product.categoryId,
          brandId: Product.brandId,
        })
        .from(Product)
        .where(productFilter)
        .orderBy(desc(Product.createdAt))
        .limit(maxLimit);
      const categories = await tx
        .select({ id: Category.id, name: Category.name })
        .from(Category)
        .where(eq(Category.workspaceId, workspaceId));
      const brands = await tx
        .select({ id: Brand.id, name: Brand.name })
        .from(Brand)
        .where(eq(Brand.workspaceId, workspaceId));
      const existing = await tx
        .select({
          productId: ProductEmbedding.productId,
          contentHash: ProductEmbedding.contentHash,
        })
        .from(ProductEmbedding)
        .where(eq(ProductEmbedding.workspaceId, workspaceId));

      const catMap = new Map(categories.map((c) => [c.id, c.name]));
      const brandMap = new Map(brands.map((b) => [b.id, b.name]));
      existingHashes = new Map(
        existing.map((e) => [e.productId, e.contentHash]),
      );

      catalogRows = products.map((p) => ({
        ...p,
        categoryName: p.categoryId ? (catMap.get(p.categoryId) ?? null) : null,
        brandName: p.brandId ? (brandMap.get(p.brandId) ?? null) : null,
      }));
    });
  } catch (err) {
    if (isUndefinedTableError(err)) {
      return { synced: 0, skippedUnchanged: 0, tableAvailable: false };
    }
    logger.warn(
      "Failed reading workspace products for embedding sync",
      { module: "product-matcher", workspaceId },
      err,
    );
    return { synced: 0, skippedUnchanged: 0, tableAvailable: false };
  }

  const toEmbed: {
    productId: string;
    searchDocument: string;
    contentHash: string;
  }[] = [];
  let skippedUnchanged = 0;

  for (const row of catalogRows) {
    const { searchDocument, contentHash } = buildProductSearchDocument(row);
    if (!row.id || searchDocument.length === 0) {
      continue;
    }
    if (existingHashes.get(row.id) === contentHash) {
      skippedUnchanged++;
      continue;
    }
    toEmbed.push({
      productId: row.id,
      searchDocument,
      contentHash,
    });
  }

  if (toEmbed.length === 0) {
    return { synced: 0, skippedUnchanged, tableAvailable };
  }

  // External embedding generation OUTSIDE any DB transaction (Supavisor :6543 safe)
  let vectors: number[][];
  try {
    vectors = await generateEmbeddings(
      toEmbed.map((item) => item.searchDocument),
    );
  } catch (err) {
    logger.warn(
      "Product embedding generation skipped due to provider error",
      { module: "product-matcher", workspaceId, count: toEmbed.length },
      err,
    );
    return { synced: 0, skippedUnchanged, tableAvailable };
  }

  // Short batched atomic upsert inside RLS transaction (1 round-trip per 100 rows)
  const upsertRows: {
    productId: string;
    workspaceId: string;
    contentHash: string;
    searchDocument: string;
    embedding: number[];
  }[] = [];

  for (let i = 0; i < toEmbed.length; i++) {
    const entry = toEmbed[i];
    const vec = vectors[i];
    if (!entry || !vec) continue;
    upsertRows.push({
      productId: entry.productId,
      workspaceId,
      contentHash: entry.contentHash,
      searchDocument: entry.searchDocument,
      embedding: vec,
    });
  }

  if (upsertRows.length === 0) {
    return { synced: 0, skippedUnchanged, tableAvailable };
  }

  try {
    const UPSERT_CHUNK_SIZE = 100;
    await runInWorkspaceRls(
      poolDb,
      workspaceId,
      async (tx) => {
        for (let i = 0; i < upsertRows.length; i += UPSERT_CHUNK_SIZE) {
          const chunk = upsertRows.slice(i, i + UPSERT_CHUNK_SIZE);
          await tx
            .insert(ProductEmbedding)
            .values(chunk)
            .onConflictDoUpdate({
              target: ProductEmbedding.productId,
              set: {
                contentHash: sql`excluded.content_hash`,
                searchDocument: sql`excluded.search_document`,
                embedding: sql`excluded.embedding`,
                updatedAt: sql`now()`,
              },
            });
        }
      },
      { statementTimeoutMs: 15_000 },
    );
  } catch (err) {
    if (isUndefinedTableError(err)) {
      tableAvailable = false;
      return { synced: 0, skippedUnchanged, tableAvailable };
    }
    throw err;
  }

  return { synced: upsertRows.length, skippedUnchanged, tableAvailable };
}

function resolveTaxonomySuggestion(params: {
  rawCategory: string | null | undefined;
  rawBrand: string | null | undefined;
  categories: readonly { id: string; name: string }[];
  aliases: readonly { alias: string; categoryId: string }[];
  brands: readonly { id: string; name: string }[];
}): {
  suggestedCategoryId: string | null;
  suggestedCategoryName: string | null;
  suggestedBrandId: string | null;
  suggestedBrandName: string | null;
} {
  let suggestedCategoryId: string | null = null;
  let suggestedCategoryName: string | null = null;
  let suggestedBrandId: string | null = null;
  let suggestedBrandName: string | null = null;

  const catMap = new Map(params.categories.map((c) => [c.id, c.name]));

  if (params.rawCategory && params.rawCategory.trim().length > 0) {
    const targetLower = params.rawCategory.trim().toLowerCase();
    const exactCat = params.categories.find(
      (c) => c.name.trim().toLowerCase() === targetLower,
    );
    if (exactCat) {
      suggestedCategoryId = exactCat.id;
      suggestedCategoryName = exactCat.name;
    } else {
      const aliasHit = params.aliases.find(
        (a) => a.alias.trim().toLowerCase() === targetLower,
      );
      if (aliasHit && catMap.has(aliasHit.categoryId)) {
        suggestedCategoryId = aliasHit.categoryId;
        suggestedCategoryName = catMap.get(aliasHit.categoryId) ?? null;
      } else {
        const targetTokens = normalizeTextTokens(params.rawCategory);
        let bestScore = 0;
        for (const cat of params.categories) {
          const score = lexicalSimilarityScore(
            targetTokens,
            normalizeTextTokens(cat.name),
          );
          if (score > bestScore && score >= 0.45) {
            bestScore = score;
            suggestedCategoryId = cat.id;
            suggestedCategoryName = cat.name;
          }
        }
      }
    }
  }

  if (params.rawBrand && params.rawBrand.trim().length > 0) {
    const brandLower = params.rawBrand.trim().toLowerCase();
    const exactBrand = params.brands.find(
      (b) => b.name.trim().toLowerCase() === brandLower,
    );
    if (exactBrand) {
      suggestedBrandId = exactBrand.id;
      suggestedBrandName = exactBrand.name;
    }
  }

  return {
    suggestedCategoryId,
    suggestedCategoryName,
    suggestedBrandId,
    suggestedBrandName,
  };
}

/**
 * Matches a batch of imported items (from Catalog, Inventory, or Container Packing Lists)
 * against the entire workspace catalog using:
 *   1. Exact SKU & Barcode matching (`confidence = 1.0`),
 *   2. Lexical token similarity,
 *   3. `pgvector` HNSW cosine similarity (`gemini-embedding-001` trilingual `ES`/`EN`/`ZH`),
 *   4. Reciprocal Rank Fusion (RRF) + category/brand suggestion.
 */
export async function matchImportedItemsToCatalog(
  poolDb: Db,
  workspaceId: string,
  items: readonly MatchableImportCandidate[],
): Promise<CatalogSemanticMatchResult[]> {
  if (items.length === 0) return [];

  // 1. Opportunistically sync up to 250 unindexed workspace products outside transaction
  const syncStatus = await syncWorkspaceProductEmbeddings(poolDb, workspaceId, {
    maxBatchLimit: 250,
  });

  // 2. Load workspace catalog snapshot + categories + aliases + brands in one short READ ONLY tx
  const snapshot = await runInWorkspaceRlsReadonly(
    poolDb,
    workspaceId,
    async (tx) => {
      // Sequential queries on single `tx` PoolClient
      const products = await tx
        .select({
          id: Product.id,
          sku: Product.sku,
          barcode: Product.barcode,
          name: Product.name,
          descriptionShort: Product.descriptionShort,
          categoryId: Product.categoryId,
          brandId: Product.brandId,
        })
        .from(Product)
        .where(eq(Product.workspaceId, workspaceId))
        .limit(5000);
      const categories = await tx
        .select({ id: Category.id, name: Category.name })
        .from(Category)
        .where(eq(Category.workspaceId, workspaceId));
      const aliases = await tx
        .select({
          alias: CategoryAlias.alias,
          categoryId: CategoryAlias.categoryId,
        })
        .from(CategoryAlias)
        .where(eq(CategoryAlias.workspaceId, workspaceId));
      const brands = await tx
        .select({ id: Brand.id, name: Brand.name })
        .from(Brand)
        .where(eq(Brand.workspaceId, workspaceId));
      return { products, categories, aliases, brands };
    },
  );

  const catMap = new Map(snapshot.categories.map((c) => [c.id, c.name]));
  const brandMap = new Map(snapshot.brands.map((b) => [b.id, b.name]));

  if (snapshot.products.length === 0) {
    return items.map((item, idx) => {
      const tax = resolveTaxonomySuggestion({
        rawCategory: item.categoryRaw,
        rawBrand: item.brandRaw,
        categories: snapshot.categories,
        aliases: snapshot.aliases,
        brands: snapshot.brands,
      });
      return {
        rowIndex: idx,
        classification: "new_product",
        matchMethod: "none",
        confidence: 0,
        matchedProductId: null,
        matchedProductSku: null,
        matchedProductName: null,
        ...tax,
      };
    });
  }

  const productById = new Map(snapshot.products.map((p) => [p.id, p]));
  const productByNormSku = new Map<
    string,
    (typeof snapshot.products)[number]
  >();
  const productByBarcode = new Map<
    string,
    (typeof snapshot.products)[number]
  >();
  const productTokens = new Map<string, Set<string>>();

  for (const prod of snapshot.products) {
    const skuKey = normalizeCodeKey(prod.sku);
    if (skuKey) productByNormSku.set(skuKey, prod);
    const barKey = normalizeCodeKey(prod.barcode);
    if (barKey) productByBarcode.set(barKey, prod);
    productTokens.set(prod.id, normalizeTextTokens(prod.name));
  }

  const results = new Array<CatalogSemanticMatchResult | null>(
    items.length,
  ).fill(null);
  const unresolvedIndices: number[] = [];

  // 3. Fast O(1) exact SKU / Barcode pass first (avoids unnecessary embedding calls!)
  for (let i = 0; i < items.length; i++) {
    const item = items[i];
    if (!item) continue;

    if (!item.skuAutoGenerated && item.sku) {
      const skuHit = productByNormSku.get(normalizeCodeKey(item.sku));
      if (skuHit) {
        results[i] = {
          rowIndex: i,
          classification: "matched_existing",
          matchMethod: "exact_sku",
          confidence: 1.0,
          matchedProductId: skuHit.id,
          matchedProductSku: skuHit.sku,
          matchedProductName: skuHit.name,
          suggestedCategoryId: skuHit.categoryId,
          suggestedCategoryName: skuHit.categoryId
            ? (catMap.get(skuHit.categoryId) ?? null)
            : null,
          suggestedBrandId: skuHit.brandId,
          suggestedBrandName: skuHit.brandId
            ? (brandMap.get(skuHit.brandId) ?? null)
            : null,
        };
        continue;
      }
    }

    if (item.barcode) {
      const barcodeHit = productByBarcode.get(normalizeCodeKey(item.barcode));
      if (barcodeHit) {
        results[i] = {
          rowIndex: i,
          classification: "matched_existing",
          matchMethod: "exact_barcode",
          confidence: 0.99,
          matchedProductId: barcodeHit.id,
          matchedProductSku: barcodeHit.sku,
          matchedProductName: barcodeHit.name,
          suggestedCategoryId: barcodeHit.categoryId,
          suggestedCategoryName: barcodeHit.categoryId
            ? (catMap.get(barcodeHit.categoryId) ?? null)
            : null,
          suggestedBrandId: barcodeHit.brandId,
          suggestedBrandName: barcodeHit.brandId
            ? (brandMap.get(barcodeHit.brandId) ?? null)
            : null,
        };
        continue;
      }
    }

    unresolvedIndices.push(i);
  }

  if (unresolvedIndices.length === 0) {
    return results.filter((r): r is CatalogSemanticMatchResult => r !== null);
  }

  // 4. Batched query embeddings OUTSIDE DB transaction for unresolved items
  const queryTexts = unresolvedIndices.map((idx) => {
    const item = items[idx];
    if (!item) return "";
    return [
      !item.skuAutoGenerated && item.sku ? `SKU: ${item.sku}` : "",
      `Producto: ${item.name}`,
      item.nameOriginal && item.nameOriginal !== item.name
        ? item.nameOriginal
        : "",
      item.brandRaw ? `Marca: ${item.brandRaw}` : "",
      item.categoryRaw ? `Categoría: ${item.categoryRaw}` : "",
    ]
      .filter(Boolean)
      .join(" | ");
  });

  let itemVectors: number[][] | null;
  try {
    itemVectors = await generateEmbeddings(queryTexts);
  } catch {
    itemVectors = null;
  }

  // 5. Retrieve top-3 vector neighbors per unresolved item (pgvector HNSW if 038 active, else in-memory fallback)
  const vectorTopByItem = new Map<
    number,
    { productId: string; similarity: number }[]
  >();

  if (itemVectors && syncStatus.tableAvailable) {
    try {
      const HNSW_BATCH_SIZE = 50;
      for (
        let bStart = 0;
        bStart < unresolvedIndices.length;
        bStart += HNSW_BATCH_SIZE
      ) {
        const batchEntries: { origIdx: number; vecLiteral: string }[] = [];
        const end = Math.min(
          unresolvedIndices.length,
          bStart + HNSW_BATCH_SIZE,
        );
        for (let u = bStart; u < end; u++) {
          const origIdx = unresolvedIndices[u];
          const qVec = itemVectors[u];
          if (origIdx === undefined || !qVec) continue;
          batchEntries.push({
            origIdx,
            vecLiteral: `[${qVec.map((v) => (Number.isFinite(v) ? v : 0)).join(",")}]`,
          });
        }
        if (batchEntries.length === 0) continue;

        await runInWorkspaceRlsReadonly(
          poolDb,
          workspaceId,
          async (tx) => {
            await tx.execute(
              sql`DO $$ BEGIN PERFORM set_config('hnsw.ef_search', '80', true); BEGIN PERFORM set_config('hnsw.iterative_scan', 'relaxed_order', true); EXCEPTION WHEN OTHERS THEN NULL; END; END $$;`,
            );

            // Single LATERAL round-trip per 50-item batch (Supavisor :6543 safe)
            const arrayElems = sql.join(
              batchEntries.map((b) => sql`${b.vecLiteral}`),
              sql`, `,
            );
            const lateralRes = await tx.execute<{
              ord: number;
              product_id: string;
              distance: number;
            }>(sql`
              SELECT
                q.ord::int AS ord,
                n.product_id,
                n.distance
              FROM unnest(ARRAY[${arrayElems}]::text[]) WITH ORDINALITY AS q(vec_txt, ord)
              CROSS JOIN LATERAL (
                SELECT
                  pe.product_id,
                  (pe.embedding OPERATOR(extensions.<=>) q.vec_txt::extensions.vector) AS distance
                FROM public.product_embedding pe
                WHERE pe.workspace_id = ${workspaceId}::uuid
                ORDER BY pe.embedding OPERATOR(extensions.<=>) q.vec_txt::extensions.vector ASC
                LIMIT 3
              ) n
              ORDER BY q.ord ASC, n.distance ASC
            `);

            for (const row of lateralRes.rows) {
              const entry = batchEntries[Number(row.ord) - 1];
              if (!entry) continue;
              const list = vectorTopByItem.get(entry.origIdx) ?? [];
              list.push({
                productId: row.product_id,
                similarity: Math.max(
                  0,
                  Math.min(
                    1,
                    1 -
                      (Number.isNaN(Number(row.distance))
                        ? 1
                        : Number(row.distance)),
                  ),
                ),
              });
              vectorTopByItem.set(entry.origIdx, list);
            }
          },
          { statementTimeoutMs: 15_000 },
        );
      }
    } catch (err) {
      if (!isUndefinedTableError(err)) {
        logger.warn(
          "pgvector HNSW lookup fallback triggered",
          { module: "product-matcher", workspaceId },
          err,
        );
      }
    }
  }

  if (
    vectorTopByItem.size === 0 &&
    itemVectors &&
    snapshot.products.length <= 400
  ) {
    // Graceful pre-migration-038 fallback for moderate catalogs
    try {
      const catDocs = snapshot.products.map(
        (p) =>
          buildProductSearchDocument({
            sku: p.sku,
            name: p.name,
            brandName: p.brandId ? (brandMap.get(p.brandId) ?? null) : null,
            categoryName: p.categoryId
              ? (catMap.get(p.categoryId) ?? null)
              : null,
            barcode: p.barcode,
            descriptionShort: p.descriptionShort,
          }).searchDocument,
      );
      const catVectors = await generateEmbeddings(catDocs);
      for (let u = 0; u < unresolvedIndices.length; u++) {
        const origIdx = unresolvedIndices[u];
        const qVec = itemVectors[u];
        if (origIdx === undefined || !qVec) continue;
        const scored = snapshot.products
          .map((p, cIdx) => ({
            productId: p.id,
            similarity: cosineSimilarity(qVec, catVectors[cIdx] ?? []),
          }))
          .sort((a, b) => b.similarity - a.similarity)
          .slice(0, 3);
        vectorTopByItem.set(origIdx, scored);
      }
    } catch {
      // Proceed with lexical matching only
    }
  }

  // 6. Hybrid Lexical + Semantic Vector Scoring
  for (const idx of unresolvedIndices) {
    const item = items[idx];
    if (!item) continue;

    const itemToks = normalizeTextTokens(
      `${item.name} ${item.nameOriginal ?? ""} ${item.brandRaw ?? ""}`,
    );

    let bestLexicalProdId: string | null = null;
    let bestLexicalScore = 0;
    for (const prod of snapshot.products) {
      const pToks = productTokens.get(prod.id);
      if (!pToks) continue;
      const lexScore = lexicalSimilarityScore(itemToks, pToks);
      if (lexScore > bestLexicalScore) {
        bestLexicalScore = lexScore;
        bestLexicalProdId = prod.id;
      }
    }

    const vecCandidates = vectorTopByItem.get(idx) ?? [];
    const topVec = vecCandidates[0];

    let chosenProdId: string | null = null;
    let combinedConfidence = 0;
    let matchMethod: CatalogSemanticMatchResult["matchMethod"] = "none";

    if (
      bestLexicalProdId !== null &&
      bestLexicalProdId === topVec?.productId &&
      bestLexicalScore >= 0.45 &&
      topVec.similarity >= 0.65
    ) {
      // Strong agreement between vector semantics and lexical tokens (Hybrid RRF boost)
      chosenProdId = topVec.productId;
      combinedConfidence = Math.min(
        0.98,
        topVec.similarity * 0.65 + bestLexicalScore * 0.35 + 0.05,
      );
      matchMethod = "hybrid_rrf";
    } else if (topVec && topVec.similarity >= 0.74) {
      chosenProdId = topVec.productId;
      combinedConfidence = topVec.similarity;
      matchMethod = "semantic_vector";
    } else if (bestLexicalProdId && bestLexicalScore >= 0.55) {
      chosenProdId = bestLexicalProdId;
      combinedConfidence = Math.min(0.95, 0.35 + bestLexicalScore * 0.62);
      matchMethod = "lexical_trigram";
    }

    const roundedConf = Math.trunc(combinedConfidence * 10_000) / 10_000;
    const matchedProd = chosenProdId
      ? (productById.get(chosenProdId) ?? null)
      : null;

    const fallbackTax = resolveTaxonomySuggestion({
      rawCategory: item.categoryRaw,
      rawBrand: item.brandRaw,
      categories: snapshot.categories,
      aliases: snapshot.aliases,
      brands: snapshot.brands,
    });

    if (matchedProd && roundedConf >= 0.86) {
      results[idx] = {
        rowIndex: idx,
        classification: "matched_existing",
        matchMethod,
        confidence: roundedConf,
        matchedProductId: matchedProd.id,
        matchedProductSku: matchedProd.sku,
        matchedProductName: matchedProd.name,
        suggestedCategoryId:
          matchedProd.categoryId ?? fallbackTax.suggestedCategoryId,
        suggestedCategoryName: matchedProd.categoryId
          ? (catMap.get(matchedProd.categoryId) ?? null)
          : fallbackTax.suggestedCategoryName,
        suggestedBrandId: matchedProd.brandId ?? fallbackTax.suggestedBrandId,
        suggestedBrandName: matchedProd.brandId
          ? (brandMap.get(matchedProd.brandId) ?? null)
          : fallbackTax.suggestedBrandName,
      };
    } else if (matchedProd && roundedConf >= 0.72) {
      results[idx] = {
        rowIndex: idx,
        classification: "possible_duplicate",
        matchMethod,
        confidence: roundedConf,
        matchedProductId: matchedProd.id,
        matchedProductSku: matchedProd.sku,
        matchedProductName: matchedProd.name,
        suggestedCategoryId:
          matchedProd.categoryId ?? fallbackTax.suggestedCategoryId,
        suggestedCategoryName: matchedProd.categoryId
          ? (catMap.get(matchedProd.categoryId) ?? null)
          : fallbackTax.suggestedCategoryName,
        suggestedBrandId: matchedProd.brandId ?? fallbackTax.suggestedBrandId,
        suggestedBrandName: matchedProd.brandId
          ? (brandMap.get(matchedProd.brandId) ?? null)
          : fallbackTax.suggestedBrandName,
      };
    } else {
      results[idx] = {
        rowIndex: idx,
        classification: "new_product",
        matchMethod: "none",
        confidence: roundedConf,
        matchedProductId: null,
        matchedProductSku: null,
        matchedProductName: null,
        ...fallbackTax,
      };
    }
  }

  return results.filter((r): r is CatalogSemanticMatchResult => r !== null);
}
