/**
 * Cendaro — Multi-Tenant Catalog Semantic Indexer & Hybrid RRF Product Matcher
 *
 * Bridges workspace product catalogs (`public.product`) with `public.product_embedding`
 * (`gemini-embedding-001` 1,536-dim L2-normalized vectors + pgvector HNSW) while
 * upholding Cendaro's non-negotiable security & Supavisor (:6543) rules:
 *   1. Content-Hash Delta Indexing: computes `sha256(sku | name | brand | category | barcode)`
 *      and only generates embeddings for new or modified products (protecting Free Tier RPD).
 *   2. Zero External I/O Inside DB Transactions: all `generateEmbeddings` calls execute
 *      strictly outside `runInWorkspaceRls` / `runInWorkspaceRlsReadonly`.
 *   3. Zero Confidential Cost Exposure: `search_document` contains ONLY catalog identity
 *      fields (`sku`, `name`, `brand`, `category`, `barcode`, `descriptionShort`) — never costs.
 *   4. Hybrid Reciprocal Rank Fusion (RRF): combines exact SKU/EAN-13 barcode hits,
 *      lexical token similarity, and pgvector cosine similarity (`ES` <-> `EN` <-> `ZH`)
 *      to classify imported items into `matched_existing`, `possible_duplicate`, or `new_product`.
 *   5. Graceful Pre-Migration Degradation: if migration `038` has not yet been applied
 *      (`SQLSTATE 42P01`), falls back seamlessly to in-memory L2 cosine + lexical matching.
 */

