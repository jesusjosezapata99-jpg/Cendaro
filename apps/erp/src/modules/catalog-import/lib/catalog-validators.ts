/**
 * Cendaro — Catalog Import Validators
 *
 * Client-side validation for parsed catalog rows.
 * Supports Zero-Template uploads (editable deterministic SKU autogeneration when
 * supplier sheets/PDFs omit internal SKUs + semantic RAG duplicate warnings).
 *
 * PRD: FEATURE_PRD_CATALOG_IMPORT.md §12, §22, Appendix B
 */

import { suggestDeterministicSku } from "@cendaro/validators";

import type { CatalogImportField } from "./catalog-header-aliases";
import {
  normalizeBarcode,
  normalizeBrand,
  normalizeCategory,
  normalizeName,
  normalizeQuantity,
  normalizeSku,
  parseDecimal,
  truncateString,
} from "./catalog-normalizers";

// ── Constants ────────────────────────────────────

/** Maximum file size: 10 MB (7 MB for base64 PDFs) */
export const MAX_FILE_SIZE = 10 * 1024 * 1024;
export const MAX_PDF_FILE_SIZE = 7 * 1024 * 1024;

/** Maximum row count */
export const MAX_ROW_COUNT = 10_000;

/** Accepted MIME types */
export const ACCEPTED_MIME_TYPES = [
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", // .xlsx
  "application/vnd.ms-excel", // .xls
  "text/csv",
  "application/csv",
  "application/pdf",
];

/** Accepted file extensions */
export const ACCEPTED_EXTENSIONS = [".xlsx", ".xls", ".csv", ".pdf"];

// ── Types ────────────────────────────────────────

export interface CatalogRowError {
  code: string;
  message: string;
  severity: "error" | "warning" | "info";
}

export interface CatalogRowSemanticMatch {
  classification: "matched_existing" | "possible_duplicate" | "new_product";
  matchedSku: string | null;
  matchedName: string | null;
  confidence: number;
  matchMethod: string;
}

export interface ParsedCatalogRow {
  rowNumber: number;
  sku: string;
  /** True when `sku` was deterministically generated because the source file had no SKU column */
  skuAutoGenerated?: boolean;
  name: string;
  categoryRaw?: string;
  brandRaw?: string;
  cost?: number;
  quantity?: number;
  barcode?: string;
  weight?: number;
  volume?: number;
  description?: string;
  sourceFile?: string;
  semanticMatch?: CatalogRowSemanticMatch;
}

export interface ValidatedCatalogRow extends ParsedCatalogRow {
  status: "valid" | "warning" | "error";
  errors: CatalogRowError[];
}

// ── File Validation ──────────────────────────────

interface FileValidationResult {
  valid: boolean;
  code?: string;
  message?: string;
}

/**
 * Validate a file before parsing.
 * Checks: extension, file size, empty file.
 */
export function validateFile(file: File): FileValidationResult {
  if (file.size === 0) {
    return { valid: false, code: "EMPTY_FILE", message: "Archivo vacío" };
  }

  const dotIdx = file.name.lastIndexOf(".");
  const ext = dotIdx >= 0 ? file.name.slice(dotIdx).toLowerCase() : "";
  if (!ACCEPTED_EXTENSIONS.includes(ext)) {
    return {
      valid: false,
      code: "INVALID_FORMAT",
      message: `Formato no aceptado (${file.name}): ${ext || "sin extensión"}. Use .xlsx, .xls, .csv o .pdf`,
    };
  }

  if (ext === ".pdf" && file.size > MAX_PDF_FILE_SIZE) {
    return {
      valid: false,
      code: "FILE_TOO_LARGE",
      message: `El PDF "${file.name}" excede el límite de 7 MB`,
    };
  }

  if (file.size > MAX_FILE_SIZE) {
    return {
      valid: false,
      code: "FILE_TOO_LARGE",
      message: `El archivo "${file.name}" excede 10 MB`,
    };
  }

  return { valid: true };
}

// ── Row Parsing ──────────────────────────────────

/**
 * Parse a single row from the spreadsheet into a `ParsedCatalogRow`.
 * When the source file has no SKU column (or empty SKU cell) but has a valid
 * product name, generates an editable deterministic SKU (`AUTO-...`).
 */
export function parseRow(
  row: string[],
  headerMap: Record<string, number>,
  rowNumber: number,
): ParsedCatalogRow | null {
  const get = (field: CatalogImportField): string => {
    const idx = headerMap[field];
    return idx !== undefined ? String(row[idx] ?? "").trim() : "";
  };

  const rawSku = normalizeSku(get("sku"));
  const name = normalizeName(get("name"));

  // Skip completely empty rows (PRD §22 edge case #8)
  if (!rawSku && !name) return null;

  const categoryRaw = normalizeCategory(get("category")) || undefined;
  const brandRaw = normalizeBrand(get("brand")) || undefined;

  const skuAutoGenerated = !rawSku && Boolean(name);
  const sku = skuAutoGenerated
    ? suggestDeterministicSku({
        name,
        brand: brandRaw ?? null,
        category: categoryRaw ?? null,
        rowNumber,
      })
    : rawSku;

  const costRaw = get("cost");
  const quantityRaw = get("quantity");
  const weightRaw = get("weight");
  const volumeRaw = get("volume");
  const descriptionRaw = get("description");

  return {
    rowNumber,
    sku,
    skuAutoGenerated,
    name,
    categoryRaw,
    brandRaw,
    cost: costRaw ? (parseDecimal(costRaw) ?? undefined) : undefined,
    quantity: quantityRaw
      ? (normalizeQuantity(quantityRaw) ?? undefined)
      : undefined,
    barcode: normalizeBarcode(get("barcode")) || undefined,
    weight: weightRaw ? (parseDecimal(weightRaw) ?? undefined) : undefined,
    volume: volumeRaw ? (parseDecimal(volumeRaw) ?? undefined) : undefined,
    description: descriptionRaw || undefined,
  };
}

// ── Row Validation ───────────────────────────────

/**
 * Validate a parsed catalog row.
 */
export function validateRow(
  inputRow: ParsedCatalogRow,
  seenSkus: Set<string>,
): ValidatedCatalogRow {
  const row: ParsedCatalogRow = { ...inputRow };
  const errors: CatalogRowError[] = [];

  if (!row.sku) {
    errors.push({
      code: "REQUIRED_FIELD",
      message: '"SKU" es obligatorio pero está vacío',
      severity: "error",
    });
  }

  if (!row.name) {
    errors.push({
      code: "REQUIRED_FIELD",
      message: '"Nombre" es obligatorio pero está vacío',
      severity: "error",
    });
  }

  if (row.sku && row.sku.length > 64) {
    errors.push({
      code: "VALUE_TRUNCATED",
      message: `SKU truncado de ${row.sku.length} a 64 caracteres`,
      severity: "warning",
    });
    row.sku = row.sku.slice(0, 64);
  }

  if (row.name && row.name.length > 512) {
    const { value } = truncateString(row.name, 512);
    row.name = value;
    errors.push({
      code: "VALUE_TRUNCATED",
      message: "Nombre truncado a 512 caracteres",
      severity: "warning",
    });
  }

  if (row.skuAutoGenerated) {
    errors.push({
      code: "SKU_AUTO_GENERATED",
      message: "SKU sugerido automáticamente (editable)",
      severity: "warning",
    });
  }

  if (
    row.semanticMatch?.classification === "possible_duplicate" &&
    row.semanticMatch.matchedSku
  ) {
    errors.push({
      code: "SEMANTIC_DUPLICATE",
      message: `Posible duplicado semántico de "${row.semanticMatch.matchedSku}" (${row.semanticMatch.matchedName ?? "catálogo"})`,
      severity: "warning",
    });
  } else if (
    row.semanticMatch?.classification === "matched_existing" &&
    row.semanticMatch.matchedSku &&
    row.semanticMatch.matchMethod !== "exact_sku"
  ) {
    errors.push({
      code: "SEMANTIC_LINKED",
      message: `Vinculado por IA al SKU existente "${row.semanticMatch.matchedSku}"`,
      severity: "info",
    });
  }

  // Duplicate SKU within batch
  if (row.sku && seenSkus.has(row.sku)) {
    errors.push({
      code: "DUPLICATE_SKU_FILE",
      message: `SKU "${row.sku}" duplicado en la carga — se usa la última fila`,
      severity: "warning",
    });
  }
  if (row.sku) seenSkus.add(row.sku);

  if (row.cost !== undefined && row.cost < 0) {
    errors.push({
      code: "NEGATIVE_COST",
      message: `Costo no puede ser negativo. Recibido: "${row.cost}"`,
      severity: "error",
    });
  }

  if (row.quantity !== undefined && row.quantity < 0) {
    errors.push({
      code: "INVALID_QUANTITY",
      message: `Cantidad debe ser un entero positivo. Recibido: "${row.quantity}"`,
      severity: "error",
    });
  }

  if (row.description && row.description.length > 2000) {
    const { value } = truncateString(row.description, 2000);
    row.description = value;
    errors.push({
      code: "VALUE_TRUNCATED",
      message: "Descripción truncada a 2000 caracteres",
      severity: "warning",
    });
  }

  const hasErrors = errors.some((e) => e.severity === "error");
  const hasWarnings = errors.some((e) => e.severity === "warning");

  return {
    ...row,
    status: hasErrors ? "error" : hasWarnings ? "warning" : "valid",
    errors,
  };
}

/**
 * Validate all parsed rows.
 */
export function validateAllRows(rows: ParsedCatalogRow[]): {
  rows: ValidatedCatalogRow[];
  validCount: number;
  warningCount: number;
  errorCount: number;
} {
  const seenSkus = new Set<string>();
  const validatedRows = rows.map((row) => validateRow(row, seenSkus));

  const validCount = validatedRows.filter((r) => r.status === "valid").length;
  const warningCount = validatedRows.filter(
    (r) => r.status === "warning",
  ).length;
  const errorCount = validatedRows.filter((r) => r.status === "error").length;

  return { rows: validatedRows, validCount, warningCount, errorCount };
}
