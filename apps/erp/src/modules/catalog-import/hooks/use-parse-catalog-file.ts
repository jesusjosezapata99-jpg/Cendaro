"use client";

/**
 * Cendaro — Zero-Template Multi-File & Multi-Sheet Catalog Parser Hook
 *
 * Supports 1..N files across `.xlsx` (multi-sheet), `.xls`, `.csv`, and `.pdf`:
 *   • Tier 0: Saved tenant/supplier `ImportTemplateProfile` lookup (`0 ms`, `0` tokens).
 *   • Tier 1: Local multilingual header alias detection (`ES` / `EN` / `ZH`).
 *   • Tier 2: Gemini Free-Tier schema inference on top 25 sample rows + deterministic
 *             compilation of up to `10,000` rows (`roundMoney2`, footer suppression,
 *             editable `AUTO-...` SKU generation when supplier omits SKU).
 *   • Multimodal PDF extraction via `aiImport.extractDocumentItems`.
 */
import { useCallback, useState } from "react";
import { useMutation } from "@tanstack/react-query";
import { read, utils } from "xlsx";

import type {
  ColumnIndexMapping,
  InferredTabularSchemaResult,
  SaveTemplateProfileInput,
} from "@cendaro/validators";
import {
  compileTabularRowsDeterministically,
  computeHeaderFingerprint,
} from "@cendaro/validators";

import type { ParsedCatalogRow } from "../lib/catalog-validators";
import { useTRPC } from "~/trpc/client";
import { autoMapCatalogHeaders } from "../lib/catalog-header-aliases";
import {
  MAX_ROW_COUNT,
  parseRow,
  validateFile,
} from "../lib/catalog-validators";

// ── Types ────────────────────────────────────────

export interface CatalogAiSummary {
  fileCount: number;
  sheetCount: number;
  templateProfileHits: number;
  aiInferredSheets: number;
  aliasMatchedSheets: number;
  pdfFilesExtracted: number;
  autoGeneratedSkus: number;
  warnings: string[];
}

export interface CatalogParseResult {
  /** Parsed header row (primary sheet) */
  headers: string[];
  /** Auto-detected header mapping: field → column index */
  headerMap: Record<string, number>;
  /** Unmapped header names */
  unmapped: string[];
  /** Parsed data rows across all uploaded files/sheets */
  parsedRows: ParsedCatalogRow[];
  /** Raw string cells per row when single-schema tabular (enables manual column remapping) */
  rawDataRows?: string[][];
  /** Header row index (0-based) for accurate row numbers on re-parse */
  headerIndex?: number;
  /** Sheet / batch label */
  sheetName: string;
  /** Original filename (or multi-file summary) */
  filename: string;
  /** Selected supplier ID (optional, associated with learned template profiles) */
  supplierId?: string | null;
  /** Novel tabular schemas learned during this upload to persist on commit */
  learnedProfilesToSave?: SaveTemplateProfileInput[];
  /** Zero-Template resolution telemetry */
  aiSummary?: CatalogAiSummary;
  /** True when rows come from PDF or multi-schema merge or high-confidence (>=0.92) AI/profile */
  autoAdvanceToValidation?: boolean;
  /** True when multiple heterogeneous schemas or PDFs were merged (manual single-table column remap N/A) */
  isMultiSchemaBatch?: boolean;
}

export interface CatalogParseError {
  code: string;
  message: string;
}

export interface ParseCatalogFilesOptions {
  supplierId?: string | null;
}

export interface UseParseCatalogFileReturn {
  result: CatalogParseResult | null;
  error: CatalogParseError | null;
  isParsing: boolean;
  parseFile: (
    file: File,
    options?: ParseCatalogFilesOptions,
  ) => Promise<CatalogParseResult | null>;
  parseFiles: (
    files: File[],
    options?: ParseCatalogFilesOptions,
  ) => Promise<CatalogParseResult | null>;
  reset: () => void;
}

// ── Helpers ──────────────────────────────────────

const IGNORED_TEMPLATE_HELPER_SHEETS = new Set([
  "instrucciones",
  "instructions",
  "valores validos",
  "valores válidos",
  "referencia",
  "references",
  "leyenda",
  "legend",
]);

function isHelperSheetName(name: string): boolean {
  return IGNORED_TEMPLATE_HELPER_SHEETS.has(name.trim().toLowerCase());
}

function arrayBufferToBase64(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  const chunkSize = 0x8000;
  const parts: string[] = [];
  for (let i = 0; i < bytes.length; i += chunkSize) {
    const slice = bytes.subarray(i, i + chunkSize);
    parts.push(String.fromCharCode(...slice));
  }
  return btoa(parts.join(""));
}

function findLocalStandardHeaderRow(rows: string[][]): {
  index: number;
  headers: string[];
  map: Record<string, number>;
  unmapped: string[];
} | null {
  const maxScan = Math.min(rows.length, 20);
  for (let i = 0; i < maxScan; i++) {
    const row = rows[i];
    if (!row || row.length === 0) continue;
    const stringRow = row.map((cell) => String(cell));
    const { map, unmapped } = autoMapCatalogHeaders(stringRow);
    // Fast local path applies ONLY when standard aliases confidently cover both `sku` and `name`
    if ("sku" in map && "name" in map && Object.keys(map).length >= 2) {
      return { index: i, headers: stringRow, map, unmapped };
    }
  }
  return null;
}

function toCatalogHeaderMap(
  mapping: ColumnIndexMapping,
): Record<string, number> {
  const out: Record<string, number> = {};
  const allowedKeys = [
    "sku",
    "name",
    "category",
    "brand",
    "cost",
    "quantity",
    "barcode",
    "weight",
    "volume",
    "description",
  ] as const;
  for (const key of allowedKeys) {
    const idx = mapping[key];
    if (idx !== undefined) {
      out[key] = idx;
    }
  }
  return out;
}

// ── Hook ─────────────────────────────────────────

export function useParseCatalogFile(): UseParseCatalogFileReturn {
  const trpc = useTRPC();
  const [result, setResult] = useState<CatalogParseResult | null>(null);
  const [error, setError] = useState<CatalogParseError | null>(null);
  const [isParsing, setIsParsing] = useState(false);

  const inferSchemaMutation = useMutation(
    trpc.aiImport.inferTabularSchema.mutationOptions(),
  );
  const extractDocMutation = useMutation(
    trpc.aiImport.extractDocumentItems.mutationOptions(),
  );

  const parseFiles = useCallback(
    async (
      files: File[],
      options?: ParseCatalogFilesOptions,
    ): Promise<CatalogParseResult | null> => {
      if (files.length === 0) return null;
      if (files.length > 12) {
        setError({
          code: "TOO_MANY_FILES",
          message: "Puedes subir hasta 12 archivos simultáneamente por lote.",
        });
        return null;
      }

      setIsParsing(true);
      setError(null);
      setResult(null);

      try {
        for (const file of files) {
          const check = validateFile(file);
          if (!check.valid) {
            setError({
              code: check.code ?? "INVALID_FILE",
              message: check.message ?? `Archivo inválido: ${file.name}`,
            });
            setIsParsing(false);
            return null;
          }
        }

        const mergedRows: ParsedCatalogRow[] = [];
        const learnedProfilesMap = new Map<string, SaveTemplateProfileInput>();
        const schemaCacheByFingerprint = new Map<
          string,
          InferredTabularSchemaResult
        >();

        let primaryHeaders: string[] = [];
        let primaryHeaderMap: Record<string, number> = {};
        let primaryUnmapped: string[] = [];
        let primaryRawDataRows: string[][] | undefined;
        let primaryHeaderIndex = 0;
        let primarySheetLabel = "";
        const distinctSchemaFingerprints = new Set<string>();

        const summary: CatalogAiSummary = {
          fileCount: files.length,
          sheetCount: 0,
          templateProfileHits: 0,
          aiInferredSheets: 0,
          aliasMatchedSheets: 0,
          pdfFilesExtracted: 0,
          autoGeneratedSkus: 0,
          warnings: [],
        };

        let minConfidence = 1;
        let runningRowNumber = 2;

        for (const file of files) {
          const lowerName = file.name.toLowerCase();

          // ── Path A: Unstructured / Tabular PDF via Gemini Multimodal ──
          if (lowerName.endsWith(".pdf")) {
            const buffer = await file.arrayBuffer();
            const pdfBase64 = arrayBufferToBase64(buffer);
            const extracted = await extractDocMutation.mutateAsync({
              targetDomain: "catalog",
              filename: file.name,
              pdfBase64,
            });

            summary.pdfFilesExtracted++;

            for (const item of extracted.items) {
              if (mergedRows.length >= MAX_ROW_COUNT) break;
              if (item.skuAutoGenerated) summary.autoGeneratedSkus++;
              minConfidence = Math.min(minConfidence, item.confidence);

              mergedRows.push({
                rowNumber: runningRowNumber++,
                sku: item.sku,
                skuAutoGenerated: item.skuAutoGenerated,
                name: item.name,
                categoryRaw: item.categoryRaw,
                brandRaw: item.brandRaw,
                cost: item.unitCost ?? undefined,
                quantity: item.quantity > 0 ? item.quantity : undefined,
                barcode: item.barcode,
                weight: item.weightKg ?? undefined,
                volume: item.volumeCbm ?? undefined,
                description: item.description,
                sourceFile: file.name,
              });
            }

            distinctSchemaFingerprints.add(`pdf:${file.name}`);
            if (!primarySheetLabel) {
              primarySheetLabel = `${file.name} (PDF)`;
              primaryHeaders = [
                "SKU",
                "Nombre",
                "Categoría",
                "Marca",
                "Costo",
                "Cantidad",
              ];
              primaryHeaderMap = {
                sku: 0,
                name: 1,
                category: 2,
                brand: 3,
                cost: 4,
                quantity: 5,
              };
            }
            continue;
          }

          // ── Path B: Multi-Sheet Excel / CSV (.xlsx, .xls, .csv) ──
          const buffer = await file.arrayBuffer();
          const workbook = read(buffer, {
            type: "array",
            cellFormula: false,
            cellHTML: false,
            cellStyles: false,
          });

          const candidateSheetNames = workbook.SheetNames.filter(
            (sn) => !isHelperSheetName(sn),
          );
          const sheetsToProcess =
            candidateSheetNames.length > 0
              ? candidateSheetNames
              : workbook.SheetNames.slice(0, 1);

          for (const sheetName of sheetsToProcess) {
            const sheet = workbook.Sheets[sheetName];
            if (!sheet) continue;

            const rawRows = utils
              .sheet_to_json<string[]>(sheet, {
                header: 1,
                defval: "",
                blankrows: false,
              })
              .map((row) => row.map((cell) => String(cell)));

            if (rawRows.length < 2) continue;

            summary.sheetCount++;
            const sheetDisplay =
              files.length > 1 || sheetsToProcess.length > 1
                ? `${file.name} · ${sheetName}`
                : sheetName;

            // 1. Check fast local standard header alias match (when both SKU & Name exist)
            const localMatch = findLocalStandardHeaderRow(rawRows);
            if (localMatch && !options?.supplierId) {
              const fp = computeHeaderFingerprint(localMatch.headers);
              distinctSchemaFingerprints.add(fp);
              summary.aliasMatchedSheets++;

              const dataRows = rawRows.slice(localMatch.index + 1);
              for (const row of dataRows) {
                if (mergedRows.length >= MAX_ROW_COUNT) break;
                const parsed = parseRow(row, localMatch.map, runningRowNumber);
                if (parsed) {
                  if (parsed.skuAutoGenerated) summary.autoGeneratedSkus++;
                  parsed.sourceFile = file.name;
                  mergedRows.push(parsed);
                  runningRowNumber++;
                }
              }

              if (!primarySheetLabel) {
                primarySheetLabel = sheetDisplay;
                primaryHeaders = localMatch.headers;
                primaryHeaderMap = localMatch.map;
                primaryUnmapped = localMatch.unmapped;
                primaryRawDataRows = dataRows;
                primaryHeaderIndex = localMatch.index;
              }
              continue;
            }

            // 2. Zero-Template Server Inference (Saved Fingerprint -> Alias -> Gemini Free Tier)
            const sampleRows = rawRows
              .slice(0, 25)
              .map((r) => r.slice(0, 50).map((c) => String(c).slice(0, 500)));

            const provisionalFp = computeHeaderFingerprint(sampleRows[0] ?? []);
            let inferred =
              provisionalFp !== "0".repeat(64)
                ? schemaCacheByFingerprint.get(provisionalFp)
                : undefined;

            if (!inferred) {
              inferred = await inferSchemaMutation.mutateAsync({
                targetDomain: "catalog",
                filename: file.name,
                sheetName,
                supplierId: options?.supplierId ?? undefined,
                sampleRows,
                totalRowCount: Math.min(50_000, rawRows.length),
              });
              if (inferred.headerFingerprint !== "0".repeat(64)) {
                schemaCacheByFingerprint.set(
                  inferred.headerFingerprint,
                  inferred,
                );
              }
            }

            distinctSchemaFingerprints.add(inferred.headerFingerprint);
            minConfidence = Math.min(minConfidence, inferred.confidence);

            if (inferred.source === "template_profile") {
              summary.templateProfileHits++;
            } else if (
              inferred.source === "gemini_ai" ||
              inferred.source === "groq_fallback"
            ) {
              summary.aiInferredSheets++;
            } else {
              summary.aliasMatchedSheets++;
            }

            if (inferred.warnings.length > 0) {
              summary.warnings.push(...inferred.warnings);
            }

            // Queue novel profile for persistence upon user Commit
            if (
              inferred.source !== "template_profile" &&
              inferred.headerFingerprint !== "0".repeat(64) &&
              Object.keys(inferred.columnMapping).length >= 1
            ) {
              learnedProfilesMap.set(inferred.headerFingerprint, {
                targetDomain: "catalog",
                profileName: `${file.name.replace(/\.[^.]+$/, "").slice(0, 80)} (${sheetName.slice(0, 32)})`,
                supplierId: options?.supplierId ?? null,
                headerFingerprint: inferred.headerFingerprint,
                sampleHeaders: inferred.detectedHeaders
                  .slice(0, 50)
                  .map((h) => h.slice(0, 256)),
                columnMapping: inferred.columnMapping,
                transformRules: inferred.transformRules,
              });
            }

            // Deterministically compile all rows in this sheet
            const compiled = compileTabularRowsDeterministically(
              rawRows,
              inferred,
            );
            for (const item of compiled) {
              if (mergedRows.length >= MAX_ROW_COUNT) break;
              if (item.skuAutoGenerated) summary.autoGeneratedSkus++;
              mergedRows.push({
                rowNumber: runningRowNumber++,
                sku: item.sku,
                skuAutoGenerated: item.skuAutoGenerated,
                name: item.name,
                categoryRaw: item.categoryRaw,
                brandRaw: item.brandRaw,
                cost: item.unitCost ?? undefined,
                quantity: item.quantity > 0 ? item.quantity : undefined,
                barcode: item.barcode,
                weight: item.weightKg ?? undefined,
                volume: item.volumeCbm ?? undefined,
                description: item.description,
                sourceFile: file.name,
              });
            }

            if (!primarySheetLabel) {
              primarySheetLabel = sheetDisplay;
              primaryHeaders = inferred.detectedHeaders;
              primaryHeaderMap = toCatalogHeaderMap(inferred.columnMapping);
              primaryUnmapped = inferred.unmappedHeaders;
              primaryRawDataRows = rawRows.slice(inferred.headerRowIndex + 1);
              primaryHeaderIndex = inferred.headerRowIndex;
            }
          }
        }

        if (mergedRows.length === 0) {
          setError({
            code: "NO_DATA",
            message:
              "No se encontraron filas de productos válidas en los archivos seleccionados.",
          });
          setIsParsing(false);
          return null;
        }

        const isMultiSchemaBatch =
          distinctSchemaFingerprints.size > 1 || summary.pdfFilesExtracted > 0;
        const hasNameMapped = "name" in primaryHeaderMap;
        const autoAdvanceToValidation =
          isMultiSchemaBatch ||
          (hasNameMapped &&
            minConfidence >= 0.9 &&
            (summary.templateProfileHits > 0 || summary.aiInferredSheets > 0));

        const filenameLabel =
          files.length === 1
            ? (files[0]?.name ?? "catalogo.xlsx")
            : `${files[0]?.name ?? "lote"} (+${files.length - 1} archivos)`;

        const parseResult: CatalogParseResult = {
          headers: primaryHeaders,
          headerMap: primaryHeaderMap,
          unmapped: primaryUnmapped,
          parsedRows: mergedRows,
          rawDataRows: isMultiSchemaBatch ? undefined : primaryRawDataRows,
          headerIndex: primaryHeaderIndex,
          sheetName:
            files.length > 1
              ? `${files.length} archivos · ${summary.sheetCount + summary.pdfFilesExtracted} fuentes`
              : primarySheetLabel || "Catálogo",
          filename: filenameLabel.slice(0, 255),
          supplierId: options?.supplierId ?? null,
          learnedProfilesToSave: Array.from(learnedProfilesMap.values()),
          aiSummary: summary,
          autoAdvanceToValidation,
          isMultiSchemaBatch,
        };

        setResult(parseResult);
        setIsParsing(false);
        return parseResult;
      } catch (err) {
        const message =
          err instanceof Error && err.message
            ? err.message
            : "Error al analizar los archivos. Verifique que sean documentos Excel, CSV o PDF válidos.";
        setError({
          code: "PARSE_ERROR",
          message,
        });
        setIsParsing(false);
        return null;
      }
    },
    [extractDocMutation, inferSchemaMutation],
  );

  const parseFile = useCallback(
    async (
      file: File,
      options?: ParseCatalogFilesOptions,
    ): Promise<CatalogParseResult | null> => parseFiles([file], options),
    [parseFiles],
  );

  const reset = useCallback(() => {
    setResult(null);
    setError(null);
    setIsParsing(false);
  }, []);

  return { result, error, isParsing, parseFile, parseFiles, reset };
}
