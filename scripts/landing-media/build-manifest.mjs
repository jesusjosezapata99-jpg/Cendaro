#!/usr/bin/env node
/**
 * Publishes the encoded renditions (PLAN-2026-09-LANDING-REDESIGN F3, T3.5):
 * copies scripts/landing-media/.cache/encoded/* to
 * apps/erp/public/media/landing/<hash8>/ (hash of the contents, so the URLs
 * can be cached as immutable) and writes the typed manifest
 * apps/erp/src/app/_components/landing/media.ts used by <LandingVideo>.
 *
 * Usage (repo root): node scripts/landing-media/build-manifest.mjs
 */
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";

import { CACHE, ROOT } from "./lib/session.mjs";
import { STORYBOARDS } from "./storyboards.mjs";

const ENCODED = join(CACHE, "encoded");
const PUBLIC_DIR = join(ROOT, "apps/erp/public/media/landing");
const MANIFEST = join(
  ROOT,
  "apps/erp/src/app/_components/landing/media.ts",
);
const THEMES = ["light", "dark"];

const meta = JSON.parse(readFileSync(join(ENCODED, "meta.json"), "utf8"));

// Every storyboard must have both themes encoded.
const missing = STORYBOARDS.flatMap((clip) =>
  THEMES.filter((theme) => !meta[`${clip.id}-${theme}`]).map(
    (theme) => `${clip.id}-${theme}`,
  ),
);
if (missing.length > 0) {
  throw new Error(`Not encoded yet: ${missing.join(", ")}`);
}

const files = readdirSync(ENCODED)
  .filter((name) => /\.(webm|mp4|avif)$/.test(name))
  .sort();
const hash = createHash("sha1");
for (const name of files) {
  hash.update(name);
  hash.update(readFileSync(join(ENCODED, name)));
}
const digest = hash.digest("hex").slice(0, 8);
const dest = join(PUBLIC_DIR, digest);

// Remove the previous video directory (named in the old manifest), never the
// grain tile's directory.
if (existsSync(MANIFEST)) {
  const previous = /\/media\/landing\/([0-9a-f]{8})\//.exec(
    readFileSync(MANIFEST, "utf8"),
  )?.[1];
  if (previous && previous !== digest) {
    rmSync(join(PUBLIC_DIR, previous), { recursive: true, force: true });
  }
}
mkdirSync(dest, { recursive: true });
for (const name of files) copyFileSync(join(ENCODED, name), join(dest, name));

const url = (name) => `/media/landing/${digest}/${name}`;
const clips = Object.fromEntries(
  STORYBOARDS.map((clip) => {
    const themed = (theme) => {
      const entry = meta[`${clip.id}-${theme}`];
      return {
        poster: url(`${clip.id}-${theme}-poster.avif`),
        videos: entry.renditions.map((r) => ({
          width: r.width,
          av1: url(`${clip.id}-${theme}-${r.width}.webm`),
          h264: url(`${clip.id}-${theme}-${r.width}.mp4`),
        })),
      };
    };
    const { width, height } = meta[`${clip.id}-light`];
    return [
      clip.id,
      { id: clip.id, wide: { width, height, light: themed("light"), dark: themed("dark") } },
    ];
  }),
);

writeFileSync(
  MANIFEST,
  `/**
 * Landing recordings manifest. GENERATED by scripts/landing-media/build-manifest.mjs
 * from the encoded renditions — do not edit by hand (run
 * \`node scripts/landing-media/run-all.mjs\`). URLs carry a content hash, so
 * /media/landing/* is served with \`Cache-Control: immutable\` (next.config.js).
 */
import type { MediaClip } from "./primitives/video-policy";

export const MEDIA = ${JSON.stringify(clips, null, 2)} as const satisfies Record<string, MediaClip>;

export type ClipId = keyof typeof MEDIA;
`,
);
console.log(`Published ${files.length} files to public/media/landing/${digest}/ and wrote media.ts`);
